"""Русские абзацы, зависящие от итогов замеров."""
NB = " "


def r1(x):
    return f"{x:.1f}".replace(".", ",")


def r2(x):
    return f"{x:.2f}".replace(".", ",")


def gfmt(g):
    return f"{g:g}".replace(".", ",")


